@pytest.mark.parametrize("name", list(CASES))
def test_reviewed_parse_case(name):
    raw, expected = CASES[name]
    assert _cues(raw) == expected


def test_ratio_after_dash_is_not_a_cue():
    raw = "0:00 첫 문장.\n결과는 - 3:1 승리였습니다.\n0:05 둘째 문장."
    assert [c[2] for c in _cues(raw)] == [0.0, 5.0]


def test_two_scripts_restarting_at_zero_keep_their_own_ends():
    raw = "Hook [0:00–0:07] — 첫 대본 첫 문장.\nOutro [0:49–0:56] — 첫 대본 끝.\nHook [0:00.5–0:08] — 둘째 대본 첫 문장.\n" \
          "Closing [0:53–0:58] — 둘째 대본 끝."
    starts_ends = [(c[2], c[3]) for c in _cues(raw)]
    assert starts_ends == [(0.0, 7.0), (49.0, 56.0), (0.5, 8.0), (53.0, 58.0)]


def test_reversed_range_drops_the_end():
    assert _cues("0:08–0:00 첫 문장.\n0:10–0:15 둘째 문장.")[0][2:4] == (8.0, 10.0)
